
# Operadores de división


# /  División normal: devuelve un resultado decimal.
a = 100
b = 30

print(a / b)

# // División entera: redondea el resultado hacia abajo.
a = 100
b = 30

print(a // b)

# %  Devuelve el resto de una división.
print(20 % 5)
print(17 % 5)


